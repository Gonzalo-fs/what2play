    /**
     * @param  array{
     *     title: string,
     *     developer: string,
     *     description: string,
     *     release_year: int|null,
     *     disclaimer: string|null,
     *     video_url: string|null,
     *     price: float|null,
     *     buy_url: string|null,
     *     difficulty: string|null,
     *     audience: string|null,
     *     graphics: string|null,
     *     requirements: string|null,
     *     requirements_specs: string|null,
     *     game_length_minutes: int|null,
     *     score: float|null,
     *     genres: list<string>,
     *     modes: list<string>
     * }  $data
     */
    private function seedGame(array $data): void
    {
        $developer = Developer::query()->firstOrCreate(['name' => $data['developer']]);

        $game = Game::query()->updateOrCreate(
            ['slug' => Str::slug($data['title'])],
            [
                'developer_id' => $developer->id,
                'title' => $data['title'],
                'description' => $data['description'],
                'release_year' => $data['release_year'],
                'disclaimer' => $data['disclaimer'],
                'video_url' => $data['video_url'],
                'price' => $data['price'],
                'buy_url' => $data['buy_url'],
                'image_path' => null,
                'difficulty' => $data['difficulty'],
                'audience' => $data['audience'],
                'graphics' => $data['graphics'],
                'requirements' => $data['requirements'],
                'requirements_specs' => $data['requirements_specs'],
                'game_length_minutes' => $data['game_length_minutes'],
                'score' => $data['score'],
            ]
        );

        $genreIds = Genre::query()
            ->whereIn('name', $data['genres'])
            ->pluck('id')
            ->all();

        $modeIds = Mode::query()
            ->whereIn('name', $data['modes'])
            ->pluck('id')
            ->all();

        $game->genres()->sync($genreIds);
        $game->modes()->sync($modeIds);
    }
